// Vendor the argon2id / bcrypt / blake2b parts of `hash-wasm` into
// `src/vendor/hash-wasm/` with their Wasm binaries as importable `.wasm`
// modules. Workers forbid `WebAssembly.compile` at runtime (hash-wasm
// compiles its embedded base64 on first use), but a `.wasm` import is
// compiled at deploy time by wrangler. Re-run after bumping `hash-wasm`:
//   node scripts/vendor-hash-wasm.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..", "node_modules", "hash-wasm");
const out = join(here, "..", "src", "vendor", "hash-wasm");
mkdirSync(out, { recursive: true });

const dist = readFileSync(join(pkg, "dist", "index.esm.js"), "utf8");
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;

// `var name$x = "argon2"; var data$x = "<base64>";` pairs precede each
// `wasmJson$x = { name: name$x, data: data$x, hash: hash$x }` object.
function extractBase64(name) {
  const m = new RegExp(`var name\\$(\\w+) = "${name}";\\s*var data\\$\\1 = "([^"]+)";`).exec(dist);
  if (!m) throw new Error(`hash-wasm binary '${name}' not found in dist/index.esm.js`);
  return Buffer.from(m[2], "base64");
}

const binaries = ["argon2", "bcrypt", "blake2b"];
for (const name of binaries) writeFileSync(join(out, `${name}.wasm`), extractBase64(name));

const files = ["WASMInterface.ts", "argon2.ts", "bcrypt.ts", "blake2b.ts", "util.ts", "mutex.ts", "lockedCreate.ts"];
for (const f of files) {
  let src = readFileSync(join(pkg, "lib", f), "utf8");
  // The embedded-wasm shape becomes a precompiled module reference.
  src = src.replace(
    /import wasmJson from "\.\.\/wasm\/(\w+)\.wasm\.json";/,
    (_m, name) => `import ${name}Module from "./${name}.wasm";\nconst wasmJson: IEmbeddedWasm = { name: "${name}", module: ${name}Module };`,
  );
  if (f === "util.ts") {
    src = src.replace(
      'export type IEmbeddedWasm = { name: string; data: string; hash: string };',
      "export type IEmbeddedWasm = { name: string; module: WebAssembly.Module };",
    );
  }
  if (f === "WASMInterface.ts") {
    src = src.replace(
      /if \(!wasmModuleCache\.has\(binary\.name\)\) \{[\s\S]*?wasmModuleCache\.set\(binary\.name, promise\);\s*\}\s*const module = await wasmModuleCache\.get\(binary\.name\);/,
      "const module = binary.module;",
    );
    if (!src.includes("const module = binary.module;")) throw new Error("WASMInterface rewrite failed");
    src = src.replace(/\n\s*decodeBase64,\n/, "\n");
    src = src.replace(/const wasmModuleCache = new Map<string, Promise<WebAssembly\.Module>>\(\);\n?/, "");
  }
  if (["argon2.ts", "bcrypt.ts", "blake2b.ts"].includes(f) && !src.includes("IEmbeddedWasm")) {
    src = src.replace(/(import[^\n]*from "\.\/util";)/, '$1\nimport type { IEmbeddedWasm } from "./util";');
  }
  src = src.replace(/\t/g, "  ");
  writeFileSync(join(out, f), `// @ts-nocheck\n// Vendored from hash-wasm@${version} (MIT). Generated by scripts/vendor-hash-wasm.mjs — do not edit.\n${src}`);
}
writeFileSync(
  join(out, "index.ts"),
  `// Vendored hash-wasm@${version} (MIT, https://github.com/Daninet/hash-wasm) with
// precompiled \`.wasm\` modules. Generated by scripts/vendor-hash-wasm.mjs.
export { argon2id, argon2Verify } from "./argon2";
export { bcryptVerify } from "./bcrypt";
`,
);
writeFileSync(
  join(out, "wasm.d.ts"),
  `declare module "*.wasm" {\n  const module: WebAssembly.Module;\n  export default module;\n}\n`,
);
writeFileSync(join(out, "LICENSE"), readFileSync(join(pkg, "LICENSE"), "utf8"));
console.log(`vendored hash-wasm@${version}: ${binaries.join(", ")}`);
